import { useState } from 'react'
import { Link } from 'react-router-dom'
import {
  ArrowRight,
  Info,
  PackageSearch,
  SearchX,
  TrendingUp,
  Users,
} from 'lucide-react'
import PageHeader from '../../../components/common/PageHeader'
import CategoryIcon from '../../../components/common/CategoryIcon'
import ScoreMeter from '../../../components/common/ScoreMeter'
import Card from '../../../components/ui/Card'
import Badge from '../../../components/ui/Badge'
import { buttonClasses } from '../../../components/ui/buttonStyles'
import { categoryTone } from '../../../lib/categoryTone'
import { EmptyState, ErrorState, LoadingState } from '../../../components/feedback/StatePanel'
import { useApi } from '../../../hooks/useApi'
import { useAuth } from '../../../hooks/useAuth'
import {
  CATEGORY_LABELS,
  CATEGORY_OPTIONS,
  DEMAND_SCORE_THRESHOLD,
  DEMAND_WINDOW_DAYS,
} from '../../../lib/constants'
import { formatRelativeTime } from '../../../utils/format'
import { listOpportunities } from '../../../services/demandgap.api'

export default function DemandGapPage() {
  const { user, canSell } = useAuth()
  const [category, setCategory] = useState('')
  const demand = useApi(
    () => listOpportunities(category ? { category } : {}),
    [category],
  )

  const opportunities = Array.isArray(demand.data)
    ? demand.data
    : demand.data?.opportunities || demand.data?.content || []

  return (
    <div className="page-shell py-8 sm:py-10">
      <PageHeader
        eyebrow="DemandGap Radar"
        title={user ? `${user.fullName.split(' ')[0]}, here is where demand is unmet` : 'Where demand is unmet'}
        description="Qualified gaps in your region or preferred categories. Scores are deterministic and explainable — never generated by an AI model."
      />

      <div className="mt-6 rounded-2xl border border-leaf-200 bg-leaf-50 p-4 sm:p-5">
        <div className="flex gap-3">
          <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl bg-white text-leaf-700 shadow-sm">
            <Info className="h-5 w-5" aria-hidden="true" />
          </span>
          <div>
            <p className="text-sm font-semibold text-leaf-900">How this feed stays trustworthy</p>
            <p className="mt-1 text-xs leading-5 text-leaf-900">
              An opportunity needs at least one explicit request in the last {DEMAND_WINDOW_DAYS} days and
              a score of {DEMAND_SCORE_THRESHOLD} or more. Request counts, distinct requesters, unmatched
              searches and active supply all go into that score. Your own requests do not count for you.
            </p>
          </div>
        </div>
      </div>

      <div className="mt-5 flex flex-wrap items-center justify-between gap-3">
        <label htmlFor="category" className="text-sm font-medium text-stone-700">
          Filter by category
        </label>
        <select
          id="category"
          value={category}
          onChange={(event) => setCategory(event.target.value)}
          className="rounded-xl border border-stone-300 bg-white px-3 py-2 text-sm text-stone-800 shadow-sm focus:border-leaf-600 focus:outline-none focus:ring-2 focus:ring-leaf-600/20"
        >
          <option value="">All categories</option>
          {CATEGORY_OPTIONS.map((option) => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>
      </div>

      <div className="mt-5">
        {demand.loading ? (
          <LoadingState label="Calculating demand gaps…" />
        ) : demand.error ? (
          <ErrorState message={demand.error} onRetry={demand.reload} />
        ) : !canSell ? (
          <EmptyState
            icon={PackageSearch}
            title="Farmer account required"
            message="DemandGap opportunities are shown only to farmer and dual-role accounts. You can still browse products and submit requests."
            action={
              <Link to="/marketplace" className={buttonClasses({ variant: 'primary', size: 'sm' })}>
                Browse marketplace
              </Link>
            }
          />
        ) : opportunities.length === 0 ? (
          <EmptyState
            icon={SearchX}
            title="No qualified gaps right now"
            message={
              category
                ? 'There is no qualified opportunity in this category for your region and preferences yet. Clear the filter or check back later.'
                : 'Demand needs at least one explicit request and a score of 30 or more. Try submitting a request or check back after more demand is recorded.'
            }
            action={
              <Link to="/requests/new" className={buttonClasses({ variant: 'secondary', size: 'sm' })}>
                Submit a request
              </Link>
            }
          />
        ) : (
          <div className="grid gap-4 lg:grid-cols-2">
            {opportunities.map((opportunity) => {
              const requestParams = new URLSearchParams({
                title: opportunity.title.replace(/\s*\(\+\d+ similar\)$/, ''),
                category: opportunity.category,
                region: opportunity.region,
              })
              return (
                <Card key={opportunity.id} className="flex flex-col p-5">
                  <div className="flex items-start gap-3">
                    <span className={`flex h-11 w-11 shrink-0 items-center justify-center rounded-xl ${categoryTone(opportunity.category)}`}>
                      <CategoryIcon category={opportunity.category} className="h-5 w-5" />
                    </span>
                    <div className="min-w-0 flex-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <Badge tone="green">Qualified</Badge>
                        <span className="text-xs font-medium text-stone-500">{opportunity.region}</span>
                      </div>
                      <h2 className="mt-2 font-semibold leading-6 text-stone-900">{opportunity.title}</h2>
                      <p className="mt-0.5 text-xs text-stone-500">
                        {CATEGORY_LABELS[opportunity.category] || opportunity.category} · updated{' '}
                        {formatRelativeTime(opportunity.lastDemandAt)}
                      </p>
                    </div>
                  </div>

                  <div className="mt-4 grid grid-cols-3 gap-2 rounded-xl bg-stone-50 p-3 text-center">
                    <div>
                      <p className="inline-flex items-center gap-1 text-xs text-stone-500">
                        <TrendingUp className="h-3.5 w-3.5" aria-hidden="true" /> Requests
                      </p>
                      <p className="mt-1 text-lg font-bold text-stone-900">{opportunity.requestCount}</p>
                    </div>
                    <div>
                      <p className="inline-flex items-center gap-1 text-xs text-stone-500">
                        <Users className="h-3.5 w-3.5" aria-hidden="true" /> People
                      </p>
                      <p className="mt-1 text-lg font-bold text-stone-900">{opportunity.distinctRequesters}</p>
                    </div>
                    <div>
                      <p className="inline-flex items-center gap-1 text-xs text-stone-500">
                        <SearchX className="h-3.5 w-3.5" aria-hidden="true" /> Searches
                      </p>
                      <p className="mt-1 text-lg font-bold text-stone-900">{opportunity.unmatchedSearches}</p>
                    </div>
                  </div>

                  <div className="mt-4">
                    <ScoreMeter score={opportunity.score} threshold={opportunity.threshold || DEMAND_SCORE_THRESHOLD} />
                  </div>

                  <details className="mt-3 rounded-xl border border-stone-200 p-3 text-xs text-stone-600">
                    <summary className="cursor-pointer font-medium text-stone-800">Why this qualified</summary>
                    <p className="mt-2 leading-5">{opportunity.reason}</p>
                  </details>

                  <div className="mt-auto flex flex-wrap items-center gap-2 pt-4">
                    <Link
                      to={`/products/new?${requestParams.toString()}`}
                      className={buttonClasses({ variant: 'primary', size: 'sm' })}
                    >
                      List a matching product <ArrowRight className="h-4 w-4" aria-hidden="true" />
                    </Link>
                    <Link
                      to="/marketplace"
                      className={buttonClasses({ variant: 'ghost', size: 'sm' })}
                    >
                      See supply
                    </Link>
                  </div>
                </Card>
              )
            })}
          </div>
        )}
      </div>
    </div>
  )
}
