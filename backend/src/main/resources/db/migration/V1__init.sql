CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name            VARCHAR(120) NOT NULL,
    phone                VARCHAR(10) NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    role                 VARCHAR(20) NOT NULL,
    region               VARCHAR(80) NOT NULL,
    preferred_categories VARCHAR(255),
    notify_opt_in        BOOLEAN NOT NULL DEFAULT TRUE,
    contact_visible      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_phone UNIQUE (phone),
    CONSTRAINT ck_users_role CHECK (role IN ('FARMER', 'CUSTOMER', 'BOTH'))
);

CREATE TABLE products (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          BIGINT NOT NULL REFERENCES users (id),
    title              VARCHAR(140) NOT NULL,
    description        VARCHAR(2000) NOT NULL,
    category           VARCHAR(30) NOT NULL,
    price              NUMERIC(12, 2) NOT NULL,
    currency           VARCHAR(3) NOT NULL DEFAULT 'INR',
    quantity_available NUMERIC(12, 2) NOT NULL,
    unit               VARCHAR(20) NOT NULL,
    listing_status     VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    language           VARCHAR(5) NOT NULL DEFAULT 'en',
    region             VARCHAR(80) NOT NULL,
    image_url          VARCHAR(500),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_quantity CHECK (quantity_available >= 0),
    CONSTRAINT ck_products_status CHECK (listing_status IN ('ACTIVE', 'INACTIVE', 'SOLD')),
    CONSTRAINT ck_products_category CHECK (category IN ('MACHINERY', 'TOOLS', 'IRRIGATION', 'SEEDS', 'FERTILIZERS', 'PESTICIDES', 'OTHER')),
    CONSTRAINT ck_products_unit CHECK (unit IN ('PIECE', 'KG', 'LITRE', 'BAG', 'QUINTAL'))
);

CREATE INDEX idx_products_status_category_region
    ON products (listing_status, category, region);
CREATE INDEX idx_products_seller ON products (seller_id);
CREATE INDEX idx_products_created_at ON products (created_at DESC);

CREATE TABLE search_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    query        VARCHAR(200) NOT NULL,
    category     VARCHAR(30),
    region       VARCHAR(80),
    language     VARCHAR(5) NOT NULL DEFAULT 'en',
    matched      BOOLEAN NOT NULL,
    result_count INTEGER NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_search_events_demand
    ON search_events (matched, category, region, created_at DESC);
CREATE INDEX idx_search_events_user ON search_events (user_id);

CREATE TABLE product_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES users (id),
    title       VARCHAR(140) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    category    VARCHAR(30) NOT NULL,
    region      VARCHAR(80) NOT NULL,
    quantity    NUMERIC(12, 2) NOT NULL,
    unit        VARCHAR(20) NOT NULL,
    language    VARCHAR(5) NOT NULL DEFAULT 'en',
    status      VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_request_quantity CHECK (quantity > 0),
    CONSTRAINT ck_request_status CHECK (status IN ('OPEN', 'FULFILLED', 'CANCELLED')),
    CONSTRAINT ck_request_category CHECK (category IN ('MACHINERY', 'TOOLS', 'IRRIGATION', 'SEEDS', 'FERTILIZERS', 'PESTICIDES', 'OTHER')),
    CONSTRAINT ck_request_unit CHECK (unit IN ('PIECE', 'KG', 'LITRE', 'BAG', 'QUINTAL'))
);

CREATE INDEX idx_requests_demand
    ON product_requests (status, category, region, created_at DESC);
CREATE INDEX idx_requests_requester ON product_requests (requester_id);

CREATE TABLE demand_opportunities (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(160) NOT NULL,
    category            VARCHAR(30) NOT NULL,
    region              VARCHAR(80) NOT NULL,
    score               NUMERIC(5, 2) NOT NULL,
    threshold           NUMERIC(5, 2) NOT NULL,
    request_count       INTEGER NOT NULL,
    distinct_requesters INTEGER NOT NULL,
    unmatched_searches  INTEGER NOT NULL,
    active_listings     INTEGER NOT NULL,
    reason              VARCHAR(500) NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    last_demand_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_opportunity_category_region UNIQUE (category, region),
    CONSTRAINT ck_opportunity_score CHECK (score >= 0 AND score <= 100),
    CONSTRAINT ck_opportunity_status CHECK (status IN ('OPEN', 'EXPIRED'))
);

CREATE INDEX idx_opportunities_open_score
    ON demand_opportunities (status, score DESC);

CREATE TABLE notifications (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type                    VARCHAR(30) NOT NULL,
    title                   VARCHAR(160) NOT NULL,
    message                 VARCHAR(500) NOT NULL,
    is_read                 BOOLEAN NOT NULL DEFAULT FALSE,
    related_product_id      BIGINT,
    related_request_id      BIGINT,
    related_opportunity_id  BIGINT,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notification_type CHECK (type IN ('DEMAND_OPPORTUNITY', 'REQUEST_MATCH', 'REQUEST_UPDATE', 'SYSTEM'))
);

CREATE INDEX idx_notifications_user_created
    ON notifications (user_id, created_at DESC);
CREATE INDEX idx_notifications_unread
    ON notifications (user_id, is_read);
